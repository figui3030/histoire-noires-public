// ============================================================
// Habillage narratif : transforme un "fait" brut du moteur
// (ex: "son prénom contient exactement 5 lettres") en phrase
// dans le ton de l'histoire.
// ============================================================
function makeNarrator(templates) {
  return function narrate(fait, index) {
    const template = templates[index % templates.length];
    const n = 3 + ((index * 7) % 17);
    return template.replace(/\{fait\}/g, fait).replace(/\{n\}/g, n);
  };
}

